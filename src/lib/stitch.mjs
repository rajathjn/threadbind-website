// Each stitch is a list of strokes (SVG path data). A cross-stitch is two strokes.
export function stitchText(text) {
  const inset = 2;
  let x = 0;
  const stitches = [];
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS[' '];
    glyph.forEach((row, r) => [...row].forEach((bit, c) => {
      if (bit !== '1') return;
      const sx = (x + c) * S, sy = r * S;
      stitches.push([
        `M${sx + inset} ${sy + S - inset}L${sx + S - inset} ${sy + inset}`,
        `M${sx + inset} ${sy + inset}L${sx + S - inset} ${sy + S - inset}`,
      ]);
    }));
    x += glyph[0].length + 1;
  }
  return { stitches, width: (x - 1) * S, height: 7 * S, strokeWidth: 2.6 };
}

// The lattice mark's 45° bars sampled onto a stitch grid and sewn the way embroiderers sew
// diagonals: runs of half-stitches that follow each bar.
export function stitchLattice(G = 45) {
  const N = 4, cell = 17, origin = 50 - (N * cell) / 2;
  const bars = [];
  for (let i = 0; i < N; i++) for (let j = 0; j < N; j++) {
    const cx = origin + j * cell + cell / 2, cy = origin + i * cell + cell / 2;
    for (const o of [-3.6, 3.6]) {
      bars.push((i + j) % 2 === 0 ? [cx - 7, cy + o - 2.3, 14, 4.6, true] : [cx + o - 2.3, cy - 7, 4.6, 14, false]);
    }
  }
  const stitches = [];
  const a = -Math.PI / 4;
  for (let gy = 0; gy < G; gy++) for (let gx = 0; gx < G; gx++) {
    // Centre of this stitch in the mark's 0-100 space, rotated back by 45° into bar space.
    const px = ((gx + 0.5) / G) * 100 - 50, py = ((gy + 0.5) / G) * 100 - 50;
    const x = px * Math.cos(a) - py * Math.sin(a) + 50, y = px * Math.sin(a) + py * Math.cos(a) + 50;
    const bar = bars.find(([bx, by, bw, bh]) => x >= bx && x <= bx + bw && y >= by && y <= by + bh);
    if (!bar) continue;
    const sx = gx * S, sy = gy * S;
    // A horizontal bar in the unrotated mark runs down-right on screen; a vertical one up-right.
    stitches.push([bar[4] ? `M${sx} ${sy}L${sx + S} ${sy + S}` : `M${sx} ${sy + S}L${sx + S} ${sy}`]);
  }
  return { stitches, width: G * S, height: G * S, strokeWidth: 3.4 };
}
